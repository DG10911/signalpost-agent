#!/usr/bin/env python3
"""Tune the bot's Config against the FAITHFUL closed-loop simulator.

``tune.py`` scores configs by replaying recorded frames -- which turned out to
be cadence-sensitive and overfits decision-timing artifacts. This tuner instead
optimises against ``simulate_path`` (the full execution model: 250 ms adverse
fills, partial fills, fee layers, settlement), across a realistic regime mix, so
the selected config is robust to the timing the evaluator actually uses.

    python tune_sim.py --trials 150 --cadence 5 --paths 3

Writes ``tuned_config.json`` / ``tuned_config.py`` (same outputs as tune.py).
"""

from __future__ import annotations

import argparse
import json
import random
import statistics
from dataclasses import asdict, replace
from pathlib import Path

import bot as botmod
from simulator import SimConfig, simulate_path
from tune import SPACE

REGIMES = {
    "normal":       dict(),
    "high_vol":     dict(annual_vol=1.2),
    "thin_depth":   dict(depth=6.0),
    "strong_edge":  dict(reference_lead_seconds=8.0),
    "choppy":       dict(annual_vol=0.9, reference_lead_seconds=0.0),
    "wide_spread":  dict(base_spread=0.06),
}


def evaluate(config: "botmod.Config", cadence: float, paths: int, seed0: int) -> dict:
    vols, cashes, quals, flat = [], [], 0, 0
    n = 0
    for regime in REGIMES.values():
        sc = SimConfig(decision_interval=cadence, **regime)
        for i in range(paths):
            r = simulate_path(botmod.Bot(config=config), seed0 + i, sc)
            vols.append(r.eligible_volume_usd)
            cashes.append(r.final_cash_usd)
            flat += int(r.terminal_flat)
            quals += int(r.reached_target and r.terminal_flat)
            n += 1
    return {
        "quals": quals, "n": n, "qual_rate": quals / n, "flat_rate": flat / n,
        "median_volume": statistics.median(vols),
        "max_volume": max(vols),
        "median_cash": statistics.median(cashes),
    }


def _score(m: dict) -> tuple:
    return (m["quals"], m["flat_rate"], m["median_cash"], m["median_volume"])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trials", type=int, default=150)
    ap.add_argument("--cadence", type=float, default=5.0)
    ap.add_argument("--paths", type=int, default=3, help="paths per regime")
    ap.add_argument("--seed0", type=int, default=1000)
    ap.add_argument("--tune-seed", type=int, default=11)
    args = ap.parse_args()

    rng = random.Random(args.tune_seed)
    keys = list(SPACE)

    base = evaluate(botmod.Config(), args.cadence, args.paths, args.seed0)
    print("baseline:", json.dumps(base))

    best = None
    seen = set()
    for _ in range(args.trials):
        combo = tuple(rng.choice(SPACE[k]) for k in keys)
        if combo in seen:
            continue
        seen.add(combo)
        cfg = replace(botmod.Config(), **dict(zip(keys, combo)))
        m = evaluate(cfg, args.cadence, args.paths, args.seed0)
        if best is None or _score(m) > best[0]:
            best = (_score(m), dict(zip(keys, combo)), m, cfg)
            print("trial %4d  NEW BEST  %s" % (len(seen), json.dumps(best[1])))
            print("            %s" % json.dumps(m))

    tuned = best[3]
    Path("frozen_config.json").write_text(json.dumps(asdict(tuned), indent=2, sort_keys=True) + "\n")
    lines = ['"""Auto-generated by tune_sim.py -- do not edit by hand."""',
             "from bot import Config", "", "TUNED = Config("]
    for k, v in asdict(tuned).items():
        lines.append("    %s=%r," % (k, v))
    lines += [")", ""]
    Path("tuned_config.py").write_text("\n".join(lines) + "\n")

    print("\n=== BEST (closed-loop sim, cadence %.0fs) ===" % args.cadence)
    print(json.dumps(best[2], indent=2))
    print("params:", json.dumps(best[1], indent=2))


if __name__ == "__main__":
    main()
