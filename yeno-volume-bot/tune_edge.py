#!/usr/bin/env python3
"""Focused search over the reference-edge gate parameters.

The edge gate (price the side from btcMid vs openingTarget, enter on positive
expected edge) is what turned qualification from 0 to frequent, so this tuner
spends all its budget on the parameters that actually move that needle, scored
against the faithful closed-loop executor. Objective matches the challenge:
maximise qualifying paths (flat at $1,000), then median cash, then volume.

    python tune_edge.py --trials 120 --cadence 5 --paths 2
"""

from __future__ import annotations

import argparse
import json
import random
import statistics
from dataclasses import asdict, replace
from pathlib import Path

import bot as botmod
from simulator import SimConfig, simulate_path

REGIMES = {
    "normal":      dict(),
    "high_vol":    dict(annual_vol=1.2),
    "thin_depth":  dict(depth=6.0),
    "strong_edge": dict(reference_lead_seconds=8.0),
    "choppy":      dict(annual_vol=0.9, reference_lead_seconds=0.0),
    "wide_spread": dict(base_spread=0.06),
}

SPACE = {
    "assumed_annual_vol": [0.5, 0.7, 0.9, 1.1, 1.3, 1.6],
    "min_edge_per_share_usd": [0.0, 0.005, 0.01, 0.02, 0.03, 0.05, 0.08],
    "target_shares": [6.0, 8.0, 10.0, 12.0, 16.0],
    "max_immediate_roundtrip_loss_usd": [0.5, 0.7, 0.9, 1.2],
    "stop_loss_per_share_usd": [0.10, 0.20, 0.35, 0.60],
    "min_profit_per_share_usd": [0.0, 0.004, 0.01],
    "max_cycles_per_market": [8, 12, 20, 40],
    "entry_window_seconds": [60.0, 90.0, 120.0, 180.0],
    "final_guard_seconds": [15.0, 18.0],
    "forced_exit_seconds": [25.0, 30.0],
}


def evaluate(config, cadence, paths, seed0):
    vols, cashes, qcash, quals, flat, n = [], [], [], 0, 0, 0
    for regime in REGIMES.values():
        sc = SimConfig(decision_interval=cadence, **regime)
        for i in range(paths):
            r = simulate_path(botmod.Bot(config=config), seed0 + i, sc)
            vols.append(r.eligible_volume_usd); cashes.append(r.final_cash_usd)
            flat += int(r.terminal_flat)
            if r.reached_target and r.terminal_flat:
                quals += 1; qcash.append(r.final_cash_usd)
            n += 1
    return {
        "quals": quals, "n": n, "flat_rate": flat / n,
        "median_cash": statistics.median(cashes),
        "median_cash_qual": statistics.median(qcash) if qcash else 0.0,
        "median_volume": statistics.median(vols), "max_volume": max(vols),
    }


def _score(m):
    return (m["quals"], m["flat_rate"], m["median_cash_qual"], m["median_volume"])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trials", type=int, default=120)
    ap.add_argument("--cadence", type=float, default=5.0)
    ap.add_argument("--paths", type=int, default=2)
    ap.add_argument("--seed0", type=int, default=1000)
    ap.add_argument("--seed", type=int, default=99)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    keys = list(SPACE)
    base = evaluate(botmod.Config(use_edge_gate=True), args.cadence, args.paths, args.seed0)
    print("baseline(edge gate on, defaults):", json.dumps(base))

    best = None
    for t in range(args.trials):
        combo = tuple(rng.choice(SPACE[k]) for k in keys)
        cfg = replace(botmod.Config(use_edge_gate=True), **dict(zip(keys, combo)))
        m = evaluate(cfg, args.cadence, args.paths, args.seed0)
        if best is None or _score(m) > best[0]:
            best = (_score(m), dict(zip(keys, combo)), m, cfg)
            print("trial %3d NEW BEST %s" % (t, json.dumps(best[1])))
            print("          %s" % json.dumps(m))

    tuned = best[3]
    Path("frozen_config.json").write_text(json.dumps(asdict(tuned), indent=2, sort_keys=True) + "\n")
    lines = ['"""Auto-generated by tune_edge.py -- do not edit by hand."""',
             "from bot import Config", "", "TUNED = Config("]
    for k, v in asdict(tuned).items():
        lines.append("    %s=%r," % (k, v))
    lines += [")", ""]
    Path("tuned_config.py").write_text("\n".join(lines) + "\n")
    print("\nBEST:", json.dumps(best[2], indent=2))


if __name__ == "__main__":
    main()
